double standard_exponential(uint64_t *pcg_state) {

    for (;;) {
        uint64_t ri = xs(pcg_state);
        ri >>= 3;
        uint8_t idx = (uint8_t)(ri & 0xFF);
        ri >>= 8;
        double x = (double)ri * we_double[idx];
        if (ri < ke_double[idx])
            return x;

        /* Camino infrecuente (~1.1%) */
        if (idx == 0) {
            /* Cola derecha: generar desde ziggurat_exp_r */
            uint64_t u = xs(pcg_state);
            return ZIG_EXP_R - log1p(-(u >> 11) * (1.0 / 9007199254740992.0));
        }
        uint64_t uv = xs(pcg_state);
        double u = (uv >> 11) * (1.0 / 9007199254740992.0);
        if ((fe_double[idx - 1] - fe_double[idx]) * u + fe_double[idx] < exp(-x))
            return x;
        /* Si no calza, reintentar */
    }
}
